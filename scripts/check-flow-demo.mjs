import assert from 'node:assert/strict';
import {writeFile} from 'node:fs/promises';
import {chromium} from '../test/fixtures/frontend/node_modules/playwright/index.mjs';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1560,height:1100}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto(new URL('../docs/examples/frontend-flow.html',import.meta.url).href);
assert.match(await page.locator('[data-node="form"] .contract').innerText(),/OrderFormProps/);
assert.match(await page.locator('[data-node="api"] .contract').last().innerText(),/saveOrder\(input: OrderDraft, signal: AbortSignal\): Promise<SaveResult>/);
await page.selectOption('#scenario','save-failure');
assert.deepEqual(await page.locator('#page-impact button').evaluateAll(nodes=>nodes.map(n=>n.dataset.page)),['edit-page','list-page']);
assert.equal(await page.locator('[data-node="cache"]').count(),1,'Shared cache must not be duplicated per page');
assert.equal(await page.locator('.pages [data-node="cache"]').count(),0);
await page.locator('#page-impact [data-page="list-page"]').click();
assert.equal(await page.evaluate(()=>document.activeElement.dataset.node),'list-page');
await page.locator('#steps button').nth(4).click();
assert.match(await page.locator('#edge-citations').innerText(),/OrdersTable 마운트 상태/);
assert.equal(await page.locator('[data-node="list-page"]').evaluate(n=>n.classList.contains('affected')),true);
await page.locator('#steps button').nth(3).click();
await assert.equal(await page.locator('.node.active').count(),2);
await assert.equal(await page.locator('.node[data-node="cache"]').evaluate(n=>n.classList.contains('active')),true);
await assert.equal(await page.locator('.node[data-node="api"]').evaluate(n=>n.classList.contains('active')),true);
await page.screenshot({path:new URL('../docs/examples/frontend-flow-desktop.png',import.meta.url).pathname,fullPage:true});
await page.selectOption('#scenario','invalid');
assert.deepEqual(await page.locator('#page-impact button').evaluateAll(nodes=>nodes.map(n=>n.dataset.page)),['edit-page']);
assert.equal(await page.locator('[data-node="list-page"]').evaluate(n=>n.classList.contains('dim')),true);
assert.equal(await page.locator('.node[data-node="cache"]').evaluate(n=>n.classList.contains('dim')),true);
assert.equal(await page.locator('.node[data-node="api"]').evaluate(n=>n.classList.contains('dim')),true);
await page.setViewportSize({width:390,height:844});
await page.selectOption('#scenario','save-failure');
await page.locator('#page-impact [data-page="list-page"]').click();
assert.equal(await page.evaluate(()=>document.activeElement.dataset.node),'list-page');
await page.screenshot({path:new URL('../docs/examples/frontend-flow-mobile.png',import.meta.url).pathname,fullPage:true});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'Mobile must not overflow');
assert.deepEqual(errors,[]);
await writeFile(new URL('../docs/examples/frontend-flow-browser-check.json',import.meta.url),JSON.stringify({checkedAt:new Date().toISOString(),viewports:[[1560,1100],[390,844]],scenario:'save-failure includes editor/list pages with conditional cache subscriber; invalid excludes list/cache/api; typed contracts visible; page links focus their targets',jsErrors:errors,mobileOverflow:false},null,2)+'\n');
await browser.close();console.log('Flow browser interaction, desktop/mobile and JS checks passed');
